import { strict as assert } from "node:assert";
import { randomUUID } from "node:crypto";
import nextEnv from "@next/env";
import { createClient } from "@supabase/supabase-js";

nextEnv.loadEnvConfig(process.cwd());

const required = [
  "NEXT_PUBLIC_SUPABASE_URL",
  "NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY",
  "TEST_USER_A_EMAIL",
  "TEST_USER_A_PASSWORD",
  "TEST_USER_B_EMAIL",
  "TEST_USER_B_PASSWORD",
];
const missing = required.filter((name) => !process.env[name]);
if (missing.length) {
  console.error(`BLOCKED: missing ${missing.join(", ")}. See README.md.`);
  process.exit(2);
}

const client = () => createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY,
  { auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false } },
);
const a = client();
const b = client();
const anonymous = client();
const run = randomUUID();
const ownA = randomUUID();
const ownB = randomUUID();
const forged = randomUUID();
let failed = false;

function allowed(result, label) {
  assert.equal(result.error, null, `${label}: ${result.error?.code ?? "error"}`);
  return result.data;
}

try {
  const userA = allowed(await a.auth.signInWithPassword({
    email: process.env.TEST_USER_A_EMAIL,
    password: process.env.TEST_USER_A_PASSWORD,
  }), "sign in A").user;
  const userB = allowed(await b.auth.signInWithPassword({
    email: process.env.TEST_USER_B_EMAIL,
    password: process.env.TEST_USER_B_PASSWORD,
  }), "sign in B").user;
  assert.notEqual(userA.id, userB.id, "Two different test users are required");

  const recordA = { id: ownA, user_id: userA.id, content: `isolation-${run}-A` };
  const recordB = { id: ownB, user_id: userB.id, content: `isolation-${run}-B` };
  allowed(await a.from("foundation_checks").insert(recordA), "A inserts own record");
  allowed(await b.from("foundation_checks").insert(recordB), "B inserts own record");
  const ids = [ownA, ownB];
  assert.deepEqual(allowed(await a.from("foundation_checks").select("id").in("id", ids), "A reads").map((row) => row.id), [ownA]);
  assert.deepEqual(allowed(await b.from("foundation_checks").select("id").in("id", ids), "B reads").map((row) => row.id), [ownB]);
  console.log("PASS: A and B can create and read only their own records");

  for (const operation of [
    () => anonymous.from("foundation_checks").select("id").in("id", ids),
    () => anonymous.from("foundation_checks").insert({ ...recordA, id: forged }),
    () => anonymous.from("foundation_checks").update({ content: "unauthorized" }).eq("id", ownA),
    () => anonymous.from("foundation_checks").delete().eq("id", ownA),
  ]) {
    const result = await operation();
    assert.equal(result.error?.code, "42501", "Anonymous access must be denied by database permissions");
  }
  console.log("PASS: anonymous SELECT/INSERT/UPDATE/DELETE denied");

  const forgedInsert = await a.from("foundation_checks").insert({ ...recordB, id: forged });
  assert.equal(forgedInsert.error?.code, "42501", "Forged ownership must be denied by RLS");
  const crossDelete = allowed(await a.from("foundation_checks").delete().eq("id", ownB).select("id"), "cross-user delete request");
  assert.deepEqual(crossDelete, [], "Cross-user delete must affect zero rows");
  assert.equal(allowed(await b.from("foundation_checks").select("id").eq("id", ownB).single(), "B record remains").id, ownB);
  const update = await a.from("foundation_checks").update({ user_id: userB.id }).eq("id", ownA);
  assert.equal(update.error?.code, "42501", "UPDATE must be denied even for the owner");
  assert.equal(allowed(await a.from("foundation_checks").select("user_id").eq("id", ownA).single(), "ownership remains").user_id, userA.id);
  console.log("PASS: forged ownership, cross-user deletion and UPDATE denied");

  assert.deepEqual(allowed(await a.from("foundation_checks").delete().eq("id", ownA).select("id"), "owner delete"), [{ id: ownA }]);
  assert.deepEqual(allowed(await a.from("foundation_checks").select("id").eq("id", ownA), "deleted record absent"), []);
  console.log("PASS: owner deletion works");
} catch (error) {
  failed = true;
  console.error(`FAIL: ${error.message}`);
} finally {
  // Only IDs generated by this run, never all user data or all test users.
  for (const authenticated of [a, b]) {
    const result = await authenticated.from("foundation_checks").delete().in("id", [ownA, ownB, forged]);
    if (result.error) {
      failed = true;
      console.error(`Cleanup incomplete (${result.error.code}); run IDs: ${ownA}, ${ownB}, ${forged}`);
    }
    await authenticated.auth.signOut();
  }
}
if (failed) process.exitCode = 1;
